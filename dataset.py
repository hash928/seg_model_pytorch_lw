from torch.utils.data import Dataset
from torchvision import transforms
from PIL import Image
import torch


class ToTensor(object):

    def __call__(self, data):
        image, label = data['image'], data['label']
        return {'image': F.to_tensor(image), 'label': F.to_tensor(label)}


class Resize(object):

    def __init__(self, size):
        self.size = size

    def __call__(self, data):
        image, label = data['image'], data['label']
        return {'image': F.resize(image, self.size), 'label': F.resize(label, self.size, interpolation=InterpolationMode.BICUBIC)}


class RandomHorizontalFlip(object):
    def __init__(self, p=0.5):
        self.p = p

    def __call__(self, data):
        image, label = data['image'], data['label']

        if random.random() < self.p:
            return {'image': F.hflip(image), 'label': F.hflip(label)}

        return {'image': image, 'label': label}


class RandomVerticalFlip(object):
    def __init__(self, p=0.5):
        self.p = p

    def __call__(self, data):
        image, label = data['image'], data['label']

        if random.random() < self.p:
            return {'image': F.vflip(image), 'label': F.vflip(label)}

        return {'image': image, 'label': label}


class Normalize(object):
    def __init__(self, mean=[0.485, 0.456, 0.406], std=[0.229, 0.224, 0.225]):
        self.mean = mean
        self.std = std

    def __call__(self, sample):
        image, label = sample['image'], sample['label']
        image = F.normalize(image, self.mean, self.std)
        return {'image': image, 'label': label}
    

class FullDataset(Dataset):
    def __init__(self, image_root, gt_root, size, mode, class_colors=None, class_names=None):
        self.images = [image_root + f for f in os.listdir(image_root) if f.endswith('.jpg') or f.endswith('.png')]
        self.gts = [gt_root + f for f in os.listdir(gt_root) if f.endswith('.png')]
        self.images = sorted(self.images)
        self.gts = sorted(self.gts)
        
        # 默认的颜色映射和类别名称
        default_colors = {
            0: [(249, 250, 20)],  # 第一个类别
            1: [(77, 203, 129), (0, 0, 0)],  # 第二个类别
            2: [(61, 38, 168)],   # 第三个类别
        }
        default_names = {
            0: "类别1",
            1: "类别2",
            2: "类别3"
        }
        
        # 使用传入的配置或默认值
        self.color_to_class = class_colors if class_colors is not None else default_colors
        self.class_names = class_names if class_names is not None else default_names
        
        if mode == 'train':
            self.transform = transforms.Compose([
                Resize((size, size)),
                RandomHorizontalFlip(p=0.5),
                RandomVerticalFlip(p=0.5),
                ToTensor(),
                Normalize()
            ])
        else:
            self.transform = transforms.Compose([
                Resize((size, size)),
                ToTensor(),
                Normalize()
            ])

    def __getitem__(self, idx):
        image = self.rgb_loader(self.images[idx])
        label = self.rgb_loader(self.gts[idx])  # 使用RGB加载器加载标签
        data = {'image': image, 'label': label}
        data = self.transform(data)
        
        # 将RGB标签转换为类别索引
        label = data['label']  # [3, H, W]
        label = label.permute(1, 2, 0)  # [H, W, 3]
        label = label * 255  # 转换回0-255范围
        label = label.long()  # 转换为整数类型
        
        # 创建类别掩码
        class_mask = torch.zeros(label.shape[0], label.shape[1], dtype=torch.long)
        for class_idx, colors in self.color_to_class.items():
            for color in colors:
                color_tensor = torch.tensor(color, device=label.device)
                mask = torch.all(label == color_tensor, dim=-1)
                class_mask[mask] = class_idx
            
        data['label'] = class_mask
        return data

    def __len__(self):
        return len(self.images)

    def rgb_loader(self, path):
        with open(path, 'rb') as f:
            img = Image.open(f)
            return img.convert('RGB')

    def binary_loader(self, path):
        with open(path, 'rb') as f:
            img = Image.open(f)
            return img.convert('L')
        

